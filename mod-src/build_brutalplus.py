b = (base / 'ra2md.csf').read_bytes()
magic, version, nlabels, nstrings, unused, lang = struct.unpack_from('<4s5I', b)
pos = 24
entries = []
names = {'GUI:AIEasy': 'Classic Brutal (original AI)', 'GUI:AINormal': 'Brutal Plus Veteran', 'GUI:AIHard': 'Brutal Plus'}
for _ in range(nlabels):
    count, n = struct.unpack_from('<II', b, pos + 4)
    pos += 12
    label = b[pos:pos + n].decode('ascii')
    pos += n
    vals = []
    for _j in range(count):
        tag = b[pos:pos + 4]
        ln = struct.unpack_from('<I', b, pos + 4)[0]
        pos += 8
        value = bytes(x ^ 255 for x in b[pos:pos + ln * 2]).decode('utf-16le')
        pos += ln * 2
        extra = b''
        if tag == b'WRTS':
            nn = struct.unpack_from('<I', b, pos)[0]
            extra = b[pos:pos + 4 + nn]
            pos += 4 + nn
        vals.append((tag, value, extra))
    if label in names:
        vals = [(b' RTS', names[label], b'')]
    entries.append((label, vals))
data = bytearray(struct.pack('<4s5I', magic, version, len(entries), sum(len(v) for _, v in entries), unused, lang))
for label, vals in entries:
    raw = label.encode('ascii')
    data += b' LBL' + struct.pack('<II', len(vals), len(raw)) + raw
    for tag, value, extra in vals:
        raw = value.encode('utf-16le')
        data += tag + struct.pack('<I', len(raw) // 2) + bytes(x ^ 255 for x in raw) + extra
p = out / 'ra2md.csf'
if p.is_symlink():
    p.unlink()
p.write_bytes(data)

