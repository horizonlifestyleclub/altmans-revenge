def team(tid, name, units, script, *, defence=False, max_=2, priority=5):
    assert len(units) <= 6, tid
    tf = 'BPF_' + tid
    taskforces[tf] = {'Name': name, **{str(i): '%d,%s' % (n, u) for i, (n, u) in enumerate(units)}, 'Group': '-1'}
    teams[tid] = {
        'Name': name, 'VeteranLevel': '1', 'MindControlDecision': '0', 'Loadable': 'no', 'Full': 'no',
        'Annoyance': 'no', 'GuardSlower': 'no', 'House': '<none>', 'Recruiter': 'no', 'Autocreate': 'yes',
        'Prebuild': 'no', 'Reinforce': 'no', 'Droppod': 'no', 'UseTransportOrigin': 'no', 'Whiner': 'no',
        'LooseRecruit': 'no', 'Aggressive': 'yes', 'Suicide': 'no', 'Priority': str(priority), 'Max': str(max_),
        'TechLevel': '0', 'Group': '-1', 'OnTransOnly': 'no', 'AvoidThreats': 'no', 'IonImmune': 'no',
        'TransportsReturnOnUnload': 'no', 'AreTeamMembersRecruitable': 'no',
        'IsBaseDefense': 'yes' if defence else 'no', 'OnlyTargetHouseEnemy': 'no',
        'Script': script, 'TaskForce': tf,
    }


def cmp(n, op):  # op: 0 <, 1 <=, 2 ==, 3 >=, 4 >, 5 !=
    return struct.pack('<II', n, op).hex() + '0' * 48


def trigger(name, tid, side, *, house='<all>', cond=-1, obj='<none>', n=0, op=3, weight=(60, 10, 80), defence=False):
    """side: 0 any, 1 Allied, 2 Soviet, 3 Yuri. cond: -1 always, 0 an enemy
    owns >= n of obj (Brutal Plus sees the whole map), 1 we own >= n of obj."""
